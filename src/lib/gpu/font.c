void SetDumpFnt(int id)
{
    if (id >= 0 && id <= fontCount) {
        dumpId = id;
        GPU_printf = (int (*)())FntPrint;
    }
}

void FntLoad(int tx, int ty)
{
    u_long *texture = (u_long *)fontTexture;

    clut = LoadClut2(texture, tx, ty + 128);
    tpage = LoadTPage(texture + 128, 0, 0, tx, ty, FONT_TEX_W, FONT_TEX_H);
    fontCount = 0;
    memset(Font, 0, sizeof(Font));
}

int FntOpen(int x, int y, int w, int h, int isbg, int n)
{
    RECT tw;
    SPRT_8 *spr;
    int i;

    if (fontCount >= FONT_STREAMS)
        return -1;
    if (fontCount == 0)
        used = 0;
    Font[fontCount].unboundedWidth = (w == 0);
    if (used + n > FONT_CHARS)
        n = FONT_CHARS - used;
    setRECT(&tw, 0, 0, 256, 256);
    SetDrawMode(&Font[fontCount].mode, 0, 0, tpage, &tw);
    if (isbg) {
        SetTile(&Font[fontCount].bg);
        setRGB0(&Font[fontCount].bg, 0, 0, 0);
        SetSemiTrans(&Font[fontCount].bg, isbg == 2);
    }
    setXY0(&Font[fontCount].bg, x, y);
    setWH(&Font[fontCount].bg, w, h);
    Font[fontCount].capacity = n;
    Font[fontCount].length = 0;
    Font[fontCount].text = textPool + used;
    Font[fontCount].spr = spritePool + used;
    Font[fontCount].text[0] = '\0';
    spr = Font[fontCount].spr;
    for (i = 0; i < n; i++, spr++) {
        SetSprt8(spr);
        spr->clut = clut;
    }
    used += n;
    return fontCount++;
}

u_long *FntFlush(int id)
{
    FontStream *f;
    const signed char *text;
    SPRT_8 *spr;
    DR_MODE *ot;
    int n, x, y, right, rightmost, bottom;
    int r, g, b, nowrap;

    rightmost = 0;
    r = 128;
    g = 128;
    b = 128;
    if (id < 0 || id >= fontCount) {
        id = dumpId;
        if (!Font[id].text)
            return 0;
    }
    f = &Font[id];
    ot = &f->mode;
    text = (const signed char *)f->text;
    n = f->capacity;
    x = f->bg.x0;
    y = f->bg.y0;
    right = x + f->bg.w;
    bottom = y + f->bg.h;
    spr = f->spr;
    nowrap = f->unboundedWidth;
    TermPrim(ot);
    for (; *text && n; text++, n--) {
        int newline = 0;
        int ch;

        switch (*text) {
        case '~':
            if (*++text == 'c') {
                r = (*++text - '0') << 4;
                g = (*++text - '0') << 4;
                b = (*++text - '0') << 4;
            }
            break;
        case '\n':
            newline = 1;
            break;
        case '\t':
            x += FONT_GLYPH * 4;
            if (x >= right && !nowrap)
                newline = 1;
            break;
        default:
            ch = (unsigned char)*text;
            if ((unsigned)(ch - 'a') < 26)
                ch = (signed char)ch - ('a' - 'A') - ' ';
            else
                ch = (signed char)ch - ' ';
            setUV0(spr, (ch % 16) * FONT_GLYPH, (ch / 16) * FONT_GLYPH);
            setXY0(spr, x, y);
            setRGB0(spr, r, g, b);
            AddPrim(ot, spr++);
            x += FONT_GLYPH;
            if (x >= right && !nowrap)
                newline = 1;
            break;
        case ' ':
            x += FONT_GLYPH;
            if (x >= right && !nowrap)
                newline = 1;
            break;
        }
        if (newline) {
            if (rightmost < x)
                rightmost = x;
            y += FONT_GLYPH;
            x = f->bg.x0;
            if (y >= bottom)
                break;
        }
    }
    if (f->bg.code) {
        AddPrim(ot, &f->bg);
        if (nowrap)
            setWH(&f->bg, rightmost - f->bg.x0, y + FONT_GLYPH - f->bg.y0);
    }
    DrawOTag((u_long *)ot);
    f->length = 0;
    f->text[0] = '\0';
    return (u_long *)ot;
}

